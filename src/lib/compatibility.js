const AXIS_KEYS = ['EI', 'SN', 'TF', 'JP']

// codeA, codeB: 'ENFP' 같은 4글자
export function compareTypes(codeA, codeB) {
  const results = AXIS_KEYS.map((axisKey, i) => {
    const letterA = codeA[i]
    const letterB = codeB[i]
    const same = letterA === letterB
    const text = same ? AXIS_COMPARISON[axisKey][letterA] : AXIS_COMPARISON[axisKey].mixed
    return { axisKey, letterA, letterB, same, text }
  })
  const sameCount = results.filter((r) => r.same).length
  return { results, sameCount }
}
