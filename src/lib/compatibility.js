function summarize(results) {
  const same = results.filter((r) => r.same)
  const diff = results.filter((r) => !r.same)

  const sharedLine = same.length
    ? '둘 다 ' +
      same.map((r, i) => SHARED_TRAIT[r.letterA][i === same.length - 1 ? 'end' : 'mid']).join(', ') +
      '.'
    : null

  const diffLine = diff.length
    ? (same.length ? '대신 ' : '') +
      diff.map((r) => DIFF_AREA[r.axisKey]).join(', ') +
      '에서는 서로 속도를 맞춰가야 해요.'
    : null

  return { sharedLine, diffLine, closing: CLOSING[same.length] }
}

const AXIS_KEYS = ['EI', 'SN', 'TF', 'JP']

// codeA, codeB: 'ENFP' 같은 4글자
export function compareTypes(codeA, codeB) {
  const results = AXIS_KEYS.map((axisKey, i) => {
    const letterA = codeA[i]
    const letterB = codeB[i]
    const same = letterA === letterB
    const text = same ? AXIS_COMPARISON[axisKey][letterA] : AXIS_COMPARISON[axisKey].mixed
    return { axisKey, letterA, letterB, same, text }
  })
  const sameCount = results.filter((r) => r.same).length
  return { results, sameCount, summary: summarize(results) }
}
